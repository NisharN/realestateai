export const STRINGS: Record<Language, Strings> = { en, ar };

export const dirFor = (lang: Language): "ltr" | "rtl" => (lang === "ar" ? "rtl" : "ltr");

const ARABIC_RE = /[\u0600-\u06FF]/;
/** Deterministic script detection for a single message (mixed input counts as Arabic if any Arabic letters). */
export const detectLanguage = (text: string): Language => (ARABIC_RE.test(text) ? "ar" : "en");

export const fmtAED = (n: number, lang: Language = "en") =>
  lang === "ar" ? `${n.toLocaleString("en-US")} درهم` : `AED ${n.toLocaleString("en-US")}`;
